import { test, expect } from "@playwright/test";
import { browserLike } from "./helpers";
import path from "node:path";

test("Guided Run sheet checks", async ({ context }) => {
  const browser = browserLike(context);
  async function openRun(scenario, ref, ready) {
    const p = await browser.newPage({ viewport: { width: 1100, height: 900 } });
    p.errors = [];
    p.on("pageerror", (e) => p.errors.push(e.message));
    // Opens the Images route by its address, as the scenario URLs do.
    await p.goto(`/?scenario=${scenario}#/images`);
    await p.waitForSelector(".nav-item");
    await p.getByRole("button", { name: `Run ${ref}`, exact: true }).click();
    await p.waitForSelector(".sheet");
    await p.waitForFunction((t) => (document.querySelector(".sheet")?.innerText ?? "").includes(t), ready, { timeout: 6000 });
    return p;
  }
  const sheet = (p) => p.locator(".sheet").innerText();
  const chip = (p, label) => p.locator("button.chip", { hasText: label });
  const networkTrigger = (p) => p.locator('.sheet [role=combobox][aria-label="Network"]');
  async function openMore(p, ready) {
    await chip(p, "More options").click();
    await p.waitForFunction((t) => (document.querySelector(".sheet")?.innerText ?? "").includes(t), ready, { timeout: 15000 });
  }
  const cmdLuminance = (p) => p.locator(".sheet .cmd").evaluate((e) => {
    const canvas = document.createElement("canvas");
    canvas.width = 1;
    canvas.height = 1;
    const ctx = canvas.getContext("2d");
    ctx.fillStyle = getComputedStyle(e).backgroundColor;
    ctx.fillRect(0, 0, 1, 1);
    const [r, g, b] = ctx.getImageData(0, 0, 1, 1).data;
    return (0.299 * r + 0.587 * g + 0.114 * b) / 255;
  });
  let p = await openRun("running", "acme/orders-api:1.4", "Read the setup notes");
  await openMore(p, "Already on devnet");
  let t = await sheet(p);
  expect.soft(/Read the setup notes/.test(t) && /acme\.example/.test(t), "guided: setup notes link shows the image's own docs host").toBeTruthy();
  expect.soft(/Docker Hub page/.test(t) && /Source code/.test(t) && /github\.com/.test(t), "guided: Hub page and source links shown with their hosts").toBeTruthy();
  expect.soft((await networkTrigger(p).innerText()).trim() === "devnet", "guided: shared network devnet is selected by default").toBeTruthy();
  expect.soft(/Already on devnet/.test(t) && /db:3306/.test(t) && /queue:6379/.test(t), "guided: other containers on the network are listed with name:port").toBeTruthy();
  expect.soft(await p.locator('.sheet input[aria-label="Host port"]').first().inputValue() === "8080", "guided: the declared port is prefilled").toBeTruthy();
  expect.soft(/orders-api-data/.test(await p.locator('.sheet input[aria-label="Volume source"]').first().inputValue()) && await p.locator('.sheet input[aria-label="Path in container"]').first().inputValue() === "/data", "guided: a named volume is suggested for the declared data folder").toBeTruthy();
  expect.soft(/defaults itself/.test(t), "guided: the image's built-in defaults are listed").toBeTruthy();
  expect.soft(/Port 8080 on this Mac is already used by web\./.test(t) && !/Pick another/.test(t) && await p.locator(".sheet .banner .font-mono", { hasText: "web" }).count() === 1, "guided: warns when a host port is taken, naming the container in the code font").toBeTruthy();
  expect.soft(/built for amd64.*arm64|amd64 but your VM is arm64/.test(t), "guided: warns about a CPU mismatch").toBeTruthy();
  await expect.soft(p.getByRole("dialog", { name: "Run acme/orders-api:1.4" }), "guided: the sheet is named Run acme/orders-api:1.4").toHaveCount(1);
  const foot = p.locator(".sheet .sheet-foot");
  expect.soft(await foot.getByRole("button", { name: "Cancel", exact: true }).count() === 1 && await foot.getByRole("button", { name: "Run", exact: true }).count() === 1 && await foot.locator("button.bg-accent").count() === 1, "guided: the foot has Cancel and exactly one primary Run").toBeTruthy();
  await expect.soft(chip(p, "More options").locator("svg"), "guided: the More options chip uses the chevron").toHaveCount(1);
  await chip(p, "Show command").click();
  await expect.soft(chip(p, "Show command").locator("svg"), "guided: the Show command chip uses the chevron").toHaveCount(1);
  expect.soft(await cmdLuminance(p) > 0.5, "guided: the command is a light block, not a dark one").toBeTruthy();
  const cmd = await p.locator(".sheet .cmd").innerText();
  expect.soft(/--network devnet/.test(cmd) && /127\.0\.0\.1:8080:8080/.test(cmd) && /-v orders-api-data:\/data/.test(cmd), "guided: the docker run command is shown").toBeTruthy();
  await p.getByRole("button", { name: /Read the setup notes/ }).click();
  await p.waitForFunction(() => (window.__opened ?? []).length > 0, null, { timeout: 2000 }).catch(() => {});
  expect.soft((await p.evaluate(() => window.__opened ?? [])).some((u) => u === "https://acme.example/docs/orders"), "guided: clicking a link opens it through the app").toBeTruthy();
  const warnBanner = p.locator(".sheet .banner", { hasText: "Port 8080 on this Mac" });
  expect.soft((await warnBanner.locator(".sev").getAttribute("class")).includes("warn") && await warnBanner.locator(".select-text").count() === 1, "guided: warnings are a warn icon with selectable text").toBeTruthy();
  const useBtn = p.getByRole("button", { name: /^Use \d+ instead$/ });
  await expect.soft(useBtn, "guided: the port clash offers a button with the next free port").toHaveCount(1);
  await useBtn.click();
  const newPort = await p.locator('.sheet input[aria-label="Host port"]').first().inputValue();
  expect.soft(newPort !== "8080" && Number(newPort) > 8080 && !/Port 8080 on this Mac/.test(await p.locator(".sheet").innerText()), `guided: one click fills the free port (${newPort}) and the warning goes`).toBeTruthy();
  await p.locator('.sheet input[aria-label="Host port"]').first().fill("8080");
  await p.getByRole("button", { name: "Run", exact: true }).click();
  await p.waitForSelector(".sheet [role=alert]", { timeout: 6000 }).catch(() => {});
  const portErr = await p.locator(".sheet [role=alert]").innerText().catch(() => "");
  expect.soft(/host port is taken/i.test(portErr) && !/Error response from daemon|driver failed/i.test(await p.locator(".sheet").innerText()), `guided: Run on a port clash says it in plain words, never raw docker output (${portErr})`).toBeTruthy();
  await p.locator('.sheet input[aria-label="Host port"]').first().fill(newPort);
  await p.getByRole("button", { name: "Run", exact: true }).click();
  // The sheet hides the moment Run is pressed; the run is over when the container exists.
  await p.waitForFunction(() => window.__mock.state().ctrs.some((c) => c.image === "acme/orders-api:1.4"), null, { timeout: 6000 }).catch(() => {});
  const st = await p.evaluate(() => window.__mock.state());
  const made = st.ctrs.find((c) => c.image === "acme/orders-api:1.4");
  expect.soft(!!made && made.networks.includes("devnet"), "guided: the container is created on the shared network").toBeTruthy();
  expect.soft(!!made && made.mounts.some((m) => m.Destination === "/data"), "guided: the data volume is attached").toBeTruthy();
  expect.soft(p.errors.length === 0, `guided: no page errors ${p.errors.join("|")}`).toBeTruthy();
  await p.screenshot({ path: "/tmp/guided-after.png" });
  await p.close();
  p = await openRun("nonet", "nginx:latest", "No version is pinned");
  await openMore(p, "doesn't exist yet");
  t = await sheet(p);
  expect.soft(/devnet \(new, created for you\)/.test(await networkTrigger(p).innerText()) && /doesn't exist yet/.test(t), "nonet: says the network will be created").toBeTruthy();
  expect.soft(/"latest" can change/.test(t), "nonet: flags an unpinned version").toBeTruthy();
  await p.getByRole("button", { name: "Add a folder or volume" }).click();
  await p.getByRole("button", { name: /Choose folder/ }).last().click();
  await p.waitForFunction(() => [...document.querySelectorAll('.sheet input[aria-label="Volume source"]')].some((i) => i.value === "/Users/you/code/app"), null, { timeout: 2000 }).catch(() => {});
  await p.locator('.sheet input[aria-label="Path in container"]').last().fill("/app");
  const writable = p.getByRole("checkbox", { name: "Let the container change files here" });
  expect.soft(await writable.count() === 1 && !(await writable.isChecked()), "folder: the 'Let the container change files here' box is unchecked by default").toBeTruthy();
  await chip(p, "Show command").click();
  expect.soft(/-v \/Users\/you\/code\/app:\/app:ro/.test(await p.locator(".sheet .cmd").innerText()), "folder: the command mounts it read-only (:ro)").toBeTruthy();
  await writable.check();
  expect.soft(!/\/app:\/app:ro/.test(await p.locator(".sheet .cmd").innerText()) && /-v \/Users\/you\/code\/app:\/app/.test(await p.locator(".sheet .cmd").innerText()), "folder: ticking the box drops :ro").toBeTruthy();
  await p.locator('.sheet input[aria-label="Volume source"]').last().fill("/Users/you/Library/Keychains");
  expect.soft(/Library or hidden folders can't be shared/.test(await sheet(p)) && await writable.count() === 0, "folder: Library is refused with a plain line and no box").toBeTruthy();
  await p.locator('.sheet input[aria-label="Volume source"]').last().fill("/Users/you/code/app");
  expect.soft(await writable.isChecked(), "folder: the choice is remembered for that folder").toBeTruthy();
  await p.locator('.sheet input[aria-label="Volume source"]').last().fill("pgdata");
  expect.soft(await writable.count() === 0 && /-v pgdata:\/app(\s|$)/.test(await p.locator(".sheet .cmd").innerText()), "folder: a named volume has no box and never gets :ro").toBeTruthy();
  await p.screenshot({ path: "/tmp/guided-nonet.png" });
  await p.locator('.sheet input[aria-label="Host port"]').first().fill("8090").catch(() => {});
  await p.getByRole("button", { name: "Run", exact: true }).click();
  await p.waitForFunction(() => window.__mock.state().ctrs.some((c) => c.image === "nginx:latest" && c.networks.includes("devnet")), null, { timeout: 6000 }).catch(() => {});
  const st2 = await p.evaluate(() => window.__mock.state());
  expect.soft(st2.networks.includes("devnet"), "nonet: the network was created when running").toBeTruthy();
  expect.soft(st2.ctrs.some((c) => c.image === "nginx:latest" && c.networks.includes("devnet")), "nonet: the container joined it").toBeTruthy();
  await p.close();
  p = await openRun("running", "acme/orders-api:1.4", "Read the setup notes");
  await p.evaluate(() => { document.documentElement.dataset.theme = "dark"; });
  await chip(p, "Show command").click();
  expect.soft(await cmdLuminance(p) < 0.5, "guided: the command is a dark block in dark mode").toBeTruthy();
  await p.close();
  p = await openRun("running", "acme/orders-api:1.4", "Read the setup notes");
  await p.keyboard.press("Escape");
  await p.waitForSelector(".sheet", { state: "detached", timeout: 3000 }).catch(() => {});
  await expect.soft(p.locator(".sheet"), "keys: Escape closes the sheet when idle").toHaveCount(0);
  await p.keyboard.press("Meta+n");
  await p.waitForSelector(".sheet", { timeout: 3000 }).catch(() => {});
  await expect.soft(p.getByRole("dialog", { name: "Choose an image to run" }), "keys: Cmd+N opens the picker titled Choose an image to run").toHaveCount(1);
  await p.getByRole("textbox", { name: "Image to run", exact: true }).fill("acme/orders-api:1.4");
  await p.getByRole("button", { name: "Continue", exact: true }).click();
  await p.waitForFunction((t) => (document.querySelector(".sheet")?.innerText ?? "").includes(t), "Read the setup notes", { timeout: 6000 }).catch(() => {});
  await p.locator('.sheet input[aria-label="Host port"]').first().fill("8090");
  await p.getByRole("button", { name: "Run", exact: true }).click();
  await p.getByText(/^Started /).first().waitFor({ timeout: 6000 }).catch(() => {});
  await expect.soft(p.getByText(/^Started /), "keys: after Run from the picker the toast says Started").not.toHaveCount(0);
  await p.waitForFunction(() => !!document.activeElement?.closest('[role="row"]'), null, { timeout: 3000 }).catch(() => {});
  expect.soft(await p.evaluate(() => !!document.activeElement?.closest('[role="row"]')), "keys: the new container's row takes focus (unproven in a browser until the loop runs this)").toBeTruthy();
  await p.close();
});
