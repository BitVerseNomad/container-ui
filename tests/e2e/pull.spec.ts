import { test, expect } from "@playwright/test";
import { browserLike } from "./helpers";
import path from "node:path";

const SHEET = '[role=dialog]';
const RESULTS = '[aria-label="Search results"] [role=row]';

test("Pull sheet checks", async ({ context }) => {
  const browser = browserLike(context);
  const p = await browser.newPage({ viewport: { width: 1100, height: 900 } });
  await p.goto(`/`);
  await p.getByRole("button", { name: "New" }).waitFor();
  await p.locator(".sidebar").getByRole("link", { name: "Images", exact: true }).click();
  await p.waitForSelector("tbody tr:not(.group-row)");
  await p.getByRole("button", { name: "Pull image" }).click();
  await p.waitForSelector(SHEET);
  const drawer = p.locator(SHEET);
  expect.soft(await drawer.getByRole("heading", { name: "Pull an image" }).count() + await p.getByRole("dialog", { name: "Pull an image" }).count() >= 1, "pull: the sheet is named Pull an image").toBeTruthy();
  expect.soft(await p.getByLabel("Search Docker Hub").count() === 1 && await p.getByLabel("Image to pull").count() === 1, "pull: finding and pulling are two separate fields").toBeTruthy();
  expect.soft(/nothing is downloaded/i.test(await drawer.innerText()), "pull: says plainly that searching downloads nothing").toBeTruthy();
  await p.getByLabel("Search Docker Hub").fill("mysql");
  await p.getByRole("button", { name: "Search", exact: true }).click();
  await p.waitForSelector(RESULTS);
  const names = () => p.locator(`${RESULTS} .name`).allInnerTexts();
  let order = await names();
  expect.soft(order[0] === "mysql" && order.includes("bitnami/mysql"), `pull: results default to most stars first (${order.join(", ")})`).toBeTruthy();
  await expect.soft(drawer.locator(".chip", { hasText: "Official" }), "pull: the official image carries an Official tag, once").toHaveCount(1);
  await drawer.getByRole("button", { name: "Name", exact: true }).click();
  order = await names();
  expect.soft(order[0] === "bitnami/mysql", `pull: sorting by name puts A first (${order.join(", ")})`).toBeTruthy();
  await p.locator(RESULTS, { hasText: "bitnami/mysql" }).click();
  await expect.soft(p.locator(`${SHEET} [role=row][aria-selected="true"]`), "pull: the chosen result is highlighted").toHaveCount(1);
  expect.soft(await p.getByLabel("Image to pull").inputValue() === "bitnami/mysql", "pull: choosing a result fills the image to pull").toBeTruthy();
  await expect.soft(p.getByRole("button", { name: "Pull bitnami/mysql" }), "pull: the Pull button names what it will download").toHaveCount(1);
  await expect.soft(drawer.locator("button.bg-accent"), "pull: only one primary button").toHaveCount(1);
  await p.getByRole("button", { name: "Pull bitnami/mysql" }).click();
  await p.waitForSelector(`${SHEET} progress`, { timeout: 5000 }).catch(() => {});
  await expect.soft(drawer.locator('progress[aria-label="Pull progress"]'), "pull: progress is shown in a progress element").toHaveCount(1);
  await p.waitForSelector("text=Pulled bitnami/mysql", { timeout: 8000 }).catch(() => {});
  await expect.soft(drawer.getByRole("button", { name: /^Run bitnami\/mysql/ }), "pull: Run is offered once pulled").toHaveCount(1);
  await p.screenshot({ path: "/tmp/pull-after.png" });
  const mode = (n) => drawer.getByRole("button", { name: n, exact: true });
  expect.soft(await mode("Docker Hub").getAttribute("aria-pressed") === "true" && await mode("Other registry").getAttribute("aria-pressed") === "false", "private: Docker Hub is the mode you start in").toBeTruthy();
  await mode("Other registry").click();
  expect.soft(await mode("Other registry").getAttribute("aria-pressed") === "true", "private: switching modes marks the new mode").toBeTruthy();
  expect.soft(await p.getByLabel("Registry host").count() === 1 && await p.getByLabel("Image path").count() === 1 && await p.getByLabel("Tag").count() === 1, "private: shows host, path and tag fields").toBeTruthy();
  expect.soft(await p.getByLabel("Search Docker Hub").count() === 0 && await p.getByLabel("Image to pull").count() === 0, "private: Docker Hub search is hidden in this mode").toBeTruthy();
  expect.soft(await p.getByLabel("Tag").inputValue() === "latest", "private: the tag starts as latest").toBeTruthy();
  expect.soft(await drawer.locator("button.bg-accent").count() === 1 && await drawer.locator("button.bg-accent").isDisabled(), "private: one primary button, off until the reference is valid").toBeTruthy();
  expect.soft(/docker login <registry>/.test(await drawer.locator(".cmd code").innerText()) && /sign in first/i.test(await drawer.innerText()), "private: says up front that private images need docker login").toBeTruthy();
  await drawer.getByRole("button", { name: "GitHub (ghcr.io)" }).click();
  expect.soft(await p.getByLabel("Registry host").inputValue() === "ghcr.io", "private: the GitHub preset fills the host").toBeTruthy();
  expect.soft(/docker login ghcr\.io$/.test(await drawer.locator(".cmd code").innerText()), "private: the login command uses the chosen host").toBeTruthy();
  await drawer.getByRole("button", { name: "AWS ECR" }).click();
  expect.soft(/Replace <account> and <region>/.test(await drawer.innerText()) && await drawer.locator("button.bg-accent").isDisabled(), "private: an unfilled ECR host is refused with a reason").toBeTruthy();
  await p.getByLabel("Registry host").fill("ghcr.io");
  await p.getByLabel("Image path").fill("acme/api");
  await p.getByLabel("Tag").fill("1.4");
  await expect.soft(drawer.locator("code", { hasText: "ghcr.io/acme/api:1.4" }), "private: shows the full reference it will pull").toHaveCount(1);
  await expect.soft(p.getByRole("button", { name: "Pull ghcr.io/acme/api:1.4" }), "private: the Pull button names the reference").toHaveCount(1);
  await p.getByRole("button", { name: "Pull ghcr.io/acme/api:1.4" }).click();
  await p.waitForSelector("text=Pulled ghcr.io/acme/api:1.4", { timeout: 8000 }).catch(() => {});
  await expect.soft(drawer.locator("p.hint", { hasText: "Pulled ghcr.io/acme/api:1.4" }), "private: a successful private pull is reported").toHaveCount(1);
  await expect.soft(drawer.getByRole("button", { name: /^Run ghcr\.io\/acme\/api:1\.4/ }), "private: Run is offered after a private pull").toHaveCount(1);
  await p.getByLabel("Image path").fill("acme/private");
  await p.getByLabel("Tag").fill("1");
  await p.getByRole("button", { name: "Pull ghcr.io/acme/private:1" }).click();
  await p.waitForSelector("text=Sign in to ghcr.io first", { timeout: 8000 }).catch(() => {});
  await expect.soft(drawer.getByText("Sign in to ghcr.io first", { exact: true }), "private: an unauthorized pull says to sign in to that host, and the raw error is not the headline").toHaveCount(1);
  await expect.soft(drawer.locator(".cmd code", { hasText: /^docker login ghcr\.io$/ }), "private: the hint shows the login command").toHaveCount(1);
  await expect.soft(drawer.getByRole("button", { name: "Copy the command" }), "private: the login command can be copied").not.toHaveCount(0);
  expect.soft(await drawer.getByRole("button", { name: "Show output" }).count() === 1 && await drawer.locator('pre[aria-label="Pull output"]').count() === 0, "private: the raw output is folded under Show output").toBeTruthy();
  await mode("Docker Hub").click();
  expect.soft(await p.getByLabel("Image to pull").count() === 1 && await drawer.getByText("Sign in to ghcr.io first", { exact: true }).count() === 0, "private: going back to Docker Hub clears the sign-in hint").toBeTruthy();
  await p.screenshot({ path: "/tmp/pull-private.png" });
  await p.keyboard.press("Escape");
  await expect.soft(p.locator(SHEET), "pull: Escape closes the sheet when idle").toHaveCount(0);
});
