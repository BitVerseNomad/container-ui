use std::env;
use std::fs;
use std::path::PathBuf;

fn main() {
    println!("cargo:rerun-if-changed=../dist/index.html");
    println!("cargo:rerun-if-changed=../dist/assets/");
    
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let dist_dir = manifest_dir.join("../dist");
    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());
    
    // Copy all dist files to OUT_DIR/dist_copy
    if out_dir.join("dist_copy").exists() {
        fs::remove_dir_all(&out_dir.join("dist_copy")).unwrap();
    }
    fs::create_dir_all(&out_dir.join("dist_copy")).unwrap();
    let assets_dir = out_dir.join("dist_copy");
    
    fn copy_dir_recursive(base: &PathBuf, src: &PathBuf, dst: &PathBuf, files: &mut Vec<String>) -> Result<(), std::io::Error> {
        for entry in fs::read_dir(src)? {
            let entry = entry?;
            let path = entry.path();
            let relative = path.strip_prefix(base).unwrap().to_string_lossy().to_string();
            let dst_path = dst.join(&relative);
            if path.is_file() {
                fs::copy(&path, &dst_path)?;
                files.push(relative);
            } else if path.is_dir() {
                fs::create_dir_all(&dst_path)?;
                // Keep dst as the root destination, not dst_path
                copy_dir_recursive(base, &path, dst, files)?;
            }
        }
        Ok(())
    }
    
    let mut files = Vec::new();
    copy_dir_recursive(&dist_dir, &dist_dir, &assets_dir, &mut files).unwrap();
    
    // Generate Rust code with file contents as byte string literals
    let mut rust_code = String::new();
    rust_code.push_str("// Auto-generated by build.rs\n\n");
    rust_code.push_str("pub fn get_embedded_assets() -> std::collections::HashMap<String, &'static [u8]> {\n");
    rust_code.push_str("    let mut map = std::collections::HashMap::new();\n");
    
    for relative in &files {
        let asset_path = assets_dir.join(relative);
        let contents = fs::read(&asset_path).unwrap();
        // Escape the bytes as a Rust byte string literal
        let escaped = escape_bytes(&contents);
        rust_code.push_str(&format!(
            "    map.insert(\"{}\".to_string(), b\"{}\".as_ref());\n",
            relative, escaped
        ));
    }
    
    rust_code.push_str("    map\n");
    rust_code.push_str("}\n");
    
    let generated_file = out_dir.join("embedded_assets.rs");
    fs::write(&generated_file, rust_code).unwrap();
    
    println!("cargo:warning=Generated embedded assets for {} files", files.len());
    
    tauri_build::build()
}

fn escape_bytes(bytes: &[u8]) -> String {
    let mut result = String::new();
    for &b in bytes {
        match b {
            b'\\' => result.push_str("\\\\"),
            b'"' => result.push_str("\\\""),
            b'\n' => result.push_str("\\n"),
            b'\r' => result.push_str("\\r"),
            b'\t' => result.push_str("\\t"),
            0x20..=0x7E => result.push(b as char),
            _ => result.push_str(&format!("\\x{:02x}", b)),
        }
    }
    result
}